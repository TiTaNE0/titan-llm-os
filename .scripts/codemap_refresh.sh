#!/usr/bin/env bash
# codemap_refresh.sh - generate <git toplevel>/CODEMAP.md, a deterministic map of tracked files.
# Usage: codemap_refresh.sh [--sha <rev>] [-h|--help]
#   no --sha : always generate.
#   --sha rev: regenerate only when rev adds, deletes or renames a path (other than CODEMAP.md).
# stdout (one line): "CODEMAP: refreshed" | "CODEMAP: unchanged (no add/delete/rename)" | "CODEMAP: skipped (tracked)"
# Exit: 0 ok; 1 not a git work tree or rev does not resolve (E1); 3 bad argument (E3). Nothing is written on non-zero exit.
# Not a vault mutation: no persona gate, no telemetry. Not registered in Tool_Registry yet.
set -uo pipefail
export GIT_LITERAL_PATHSPECS=1

SHA=""; HAVE_SHA=0
while [ $# -gt 0 ]; do
  case "$1" in
    -h|--help) sed -n 2,8p "$0"; exit 0 ;;
    --sha)
      [ $# -ge 2 ] && [ -n "$2" ] || { echo "E3: --sha requires a non-empty revision" >&2; exit 3; }
      SHA="$2"; HAVE_SHA=1; shift 2 ;;
    *) echo "E3: unknown argument: $1" >&2; exit 3 ;;
  esac
done

TOP="$(git rev-parse --show-toplevel 2>/dev/null)" || { echo "E1: not a git work tree" >&2; exit 1; }
TOP="$(cd "$TOP" && pwd -P)"
cd "$TOP" || exit 1

if [ "$HAVE_SHA" = 1 ]; then
  git rev-parse --verify --quiet "$SHA^{commit}" >/dev/null || { echo "E1: cannot resolve commit: $SHA" >&2; exit 1; }
fi

if git ls-files --error-unmatch CODEMAP.md >/dev/null 2>&1; then
  echo "CODEMAP: skipped (tracked)"; exit 0
fi

if [ "$HAVE_SHA" = 1 ]; then
  CHANGED="$(git diff-tree --root --no-commit-id -r --name-status -M "$SHA" | awk -F'\t' '
    $1 ~ /^(A|D|R)/ { p = $NF; if (p != "CODEMAP.md") { print "y"; exit } }')"
  [ -n "$CHANGED" ] || { echo "CODEMAP: unchanged (no add/delete/rename)"; exit 0; }
fi

if [ -e CODEMAP.md ] || [ -L CODEMAP.md ]; then
  if [ ! -f CODEMAP.md ] || [ -L CODEMAP.md ]; then echo "CODEMAP: skipped (not a regular file)"; exit 0; fi
fi

TMPF="$(mktemp)" || exit 1
trap 'rm -f "$TMPF" "$TMPF.raw"' EXIT
{ git ls-files -z | tr '\0' '\n' | { grep -vx 'CODEMAP.md' || true; }; } | LC_ALL=C awk '
  { n = NR; p[n] = $0 }
  END {
    printf "# CODEMAP\n<!-- generated by codemap_refresh.sh; regenerated at /close_task when a commit adds, deletes or renames files. Do not hand-edit. -->\nFiles: %d\n", n
    for (i = 1; i <= n; i++) {
      d = p[i]; if (sub(/\/[^\/]*$/, "", d)) d = d "/"; else d = "./"
      print d "\t" p[i]
    }
  }' > "$TMPF.raw" || exit 1
{
  head -n 3 "$TMPF.raw"
  tail -n +4 "$TMPF.raw" | LC_ALL=C sort -t "$(printf '\t')" -k1,1 -k2,2 | LC_ALL=C awk -F'\t' '
    function flush() { if (cnt > 50) printf "- (+%d more)\n", cnt - 50 }
    $1 != cur { flush(); cur = $1; cnt = 0; printf "\n## %s\n\n", cur }
    { cnt++; if (cnt <= 50) printf "- `%s`\n", $2 }
    END { flush() }'
} > "$TMPF" || exit 1
mv -f "$TMPF" "$TOP/CODEMAP.md" || exit 1
echo "CODEMAP: refreshed"
