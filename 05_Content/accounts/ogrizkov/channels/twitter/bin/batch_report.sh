#!/usr/bin/env bash
# batch_report.sh — roll up one batch's telemetry + artifacts into batch_report.md
#
# Reads whatever exists in <run-dir>:
#   _telemetry.jsonl  (per-call execution log from trace.sh / run_traced.sh)
#   00_candidates.json 01_anchored.json 02_drafts.json 03_review.json
# Writes <run-dir>/batch_report.md — one human-readable funnel + cost + kill-rate
# summary so the operator reads ONE file instead of five raw dumps.
#
# Usage: batch_report.sh <run-dir>
# Read-only over inputs; only writes batch_report.md. Exits 0 even on partial data.

set -uo pipefail
RUN_DIR="${1:?usage: batch_report.sh <run-dir>}"
[ -d "$RUN_DIR" ] || { echo "batch_report: no such dir: $RUN_DIR" >&2; exit 1; }

command -v python3 >/dev/null 2>&1 || { echo "batch_report: needs python3" >&2; exit 1; }

RUN_DIR="$RUN_DIR" python3 - <<'PY'
import json, os, glob
from collections import defaultdict, Counter

rd = os.environ["RUN_DIR"]
def load(name):
    p = os.path.join(rd, name)
    if not os.path.exists(p): return None
    try:
        with open(p) as f: return json.load(f)
    except Exception as e:
        return {"_error": str(e)}

def load_jsonl(name):
    p = os.path.join(rd, name)
    rows = []
    if not os.path.exists(p): return rows
    with open(p) as f:
        for line in f:
            line = line.strip()
            if not line: continue
            try: rows.append(json.loads(line))
            except Exception: pass
    return rows

cand = load("00_candidates.json") or {}
anch = load("01_anchored.json") or {}
drafts = load("02_drafts.json") or {}
review = load("03_review.json") or {}
tel = load_jsonl("_telemetry.jsonl")

batch = (review.get("batch") or anch.get("batch") or cand.get("batch")
         or os.path.basename(rd.rstrip("/")))

# ---- Funnel ----
n_cand = len(cand.get("candidates", []) or [])
n_anch = len(anch.get("targets", []) or [])
n_draft = len(drafts.get("drafts", []) or [])
results = review.get("results", []) or []
status_ct = Counter(r.get("status") for r in results)
n_pass = status_ct.get("passed", 0)
n_skip = status_ct.get("skipped", 0)
n_quar = status_ct.get("quarantined", 0)
n_held = status_ct.get("held", 0)

# ---- Per-role execution (timing + token proxy) ----
role_dur = defaultdict(int); role_tin = defaultdict(int); role_tout = defaultdict(int)
role_n = Counter(); role_err = Counter()
for e in tel:
    r = e.get("role") or "unknown"
    role_n[r] += 1
    if isinstance(e.get("duration_ms"), (int, float)): role_dur[r] += int(e["duration_ms"])
    if isinstance(e.get("tokens_in"), (int, float)):  role_tin[r]  += int(e["tokens_in"])
    if isinstance(e.get("tokens_out"), (int, float)): role_tout[r] += int(e["tokens_out"])
    if e.get("outcome") == "error": role_err[r] += 1

tot_dur = sum(role_dur.values())
tot_tok = sum(role_tin.values()) + sum(role_tout.values())

# ---- Per-criterion kill rate (v3.1: results[].criteria = [{criterion,verdict,confidence,reason}]) ----
crit_fail = Counter(); crit_total = Counter(); crit_conf = defaultdict(list)
for r in results:
    for c in (r.get("criteria") or []):
        name = c.get("criterion") or "?"
        crit_total[name] += 1
        if str(c.get("verdict", "")).lower().startswith("fail"):
            crit_fail[name] += 1
        if isinstance(c.get("confidence"), (int, float)):
            crit_conf[name].append(float(c["confidence"]))

# ---- Per-vector yield (from telemetry vector tags, or anchored) ----
vec_seen = Counter(); vec_bound = Counter(); vec_ship = Counter()
for e in tel:
    v = e.get("vector")
    if v: vec_seen[v] += 1
for t in anch.get("targets", []) or []:
    v = t.get("vector") or t.get("content_pillar")
    if v: vec_bound[v] += 1
url_status = {r.get("url"): r.get("status") for r in results}
for t in anch.get("targets", []) or []:
    v = t.get("vector") or t.get("content_pillar")
    if v and url_status.get(t.get("url")) == "passed": vec_ship[v] += 1

# ---- Quarantine / skip detail ----
parked = [r for r in results if r.get("status") in ("quarantined", "skipped", "held")]

out = []
out.append(f"# Batch report — {batch}\n")
out.append("Auto-generated by `bin/batch_report.sh`. Funnel, cost, and kill-rates for one run.\n")

out.append("## Funnel\n")
out.append("| stage | count |")
out.append("|---|---|")
out.append(f"| scouted (candidates) | {n_cand} |")
out.append(f"| anchored (bound) | {n_anch} |")
out.append(f"| drafted | {n_draft} |")
out.append(f"| passed | {n_pass} |")
out.append(f"| skipped | {n_skip} |")
out.append(f"| quarantined | {n_quar} |")
out.append(f"| held | {n_held} |")
if n_cand: out.append(f"\nEnd-to-end yield: **{n_pass}/{n_cand} = {100*n_pass/n_cand:.1f}%**\n")

out.append("## Cost & latency (per role)\n")
out.append("| role | calls | errors | total ms | tok_in* | tok_out* |")
out.append("|---|---|---|---|---|---|")
for r in sorted(role_n, key=lambda x: -role_dur[x]):
    out.append(f"| {r} | {role_n[r]} | {role_err[r]} | {role_dur[r]} | {role_tin[r]} | {role_tout[r]} |")
out.append(f"| **TOTAL** | {sum(role_n.values())} | {sum(role_err.values())} | {tot_dur} | {sum(role_tin.values())} | {sum(role_tout.values())} |")
out.append("\n\\* token figures for CLI models (grok) are char/4 proxies, not exact.\n")

if crit_total:
    out.append("## Critic kill-rate by criterion\n")
    out.append("| criterion | fails / judged | avg confidence |")
    out.append("|---|---|---|")
    for name in sorted(crit_total, key=lambda x: -crit_fail[x]):
        conf = crit_conf.get(name) or []
        avg = f"{sum(conf)/len(conf):.2f}" if conf else "n/a"
        out.append(f"| {name} | {crit_fail[name]}/{crit_total[name]} | {avg} |")
    out.append("")
else:
    out.append("## Critic kill-rate by criterion\n\n_No per-criterion data in 03_review.json (pre-v3.1 schema, or no critic run)._\n")

if vec_bound or vec_seen:
    out.append("## Per-vector yield\n")
    out.append("| vector / pillar | seen | bound | shipped |")
    out.append("|---|---|---|---|")
    for v in sorted(set(vec_seen) | set(vec_bound) | set(vec_ship)):
        out.append(f"| {v} | {vec_seen.get(v,0)} | {vec_bound.get(v,0)} | {vec_ship.get(v,0)} |")
    out.append("")

if parked:
    out.append("## Quarantined / skipped / held\n")
    for r in parked:
        out.append(f"- `{r.get('status')}` — {r.get('url','?')} — {r.get('skip_reason') or r.get('critic_verdict') or ''}")
    out.append("")

with open(os.path.join(rd, "batch_report.md"), "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", os.path.join(rd, "batch_report.md"))
PY
