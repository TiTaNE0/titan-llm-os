#!/usr/bin/env bash
# DoD1: a script generates CODEMAP.md at the repo root of a kit project, a structure map agents read.
. "$(dirname "$0")/_lib.sh"
P="$(project p1)"
mkdir -p "$P/src/lib" "$P/dir with space"
echo 1 > "$P/README.md"; echo 2 > "$P/src/main.sh"; echo 3 > "$P/src/lib/util.sh"
echo 4 > "$P/dir with space/notes.md"; echo 5 > "$P/src/ü.txt"; commit "$P" init
echo junk > "$P/untracked.tmp"

# Invoked the way a project reaches it (through .vault_link), from a nested directory.
OUT="$(cd "$P/src/lib" && "$P/.vault_link/.scripts/codemap_refresh.sh")"; RC=$?
eq "exit 0" "$RC" 0; eq "stdout" "$OUT" "CODEMAP: refreshed"
[ -f "$P/CODEMAP.md" ] && pass "written at repo root" || fail "written at repo root"
[ ! -e "$P/src/lib/CODEMAP.md" ] && pass "not written in CWD" || fail "not written in CWD"
eq "line 1" "$(sed -n 1p "$P/CODEMAP.md")" "# CODEMAP"
sed -n 2p "$P/CODEMAP.md" | grep -q '^<!-- generated by codemap_refresh.sh.*Do not hand-edit. -->$' && pass "line 2 banner" || fail "line 2 banner"
eq "line 3 tracked count" "$(sed -n 3p "$P/CODEMAP.md")" "Files: 5"
for h in './' 'dir with space/' 'src/' 'src/lib/'; do grep -qxF "## $h" "$P/CODEMAP.md" && pass "heading $h" || fail "heading $h"; done
for p in README.md src/main.sh src/lib/util.sh 'dir with space/notes.md' 'src/ü.txt'; do
  grep -qxF -- "- \`$p\`" "$P/CODEMAP.md" && pass "lists $p" || fail "lists $p"; done
grep -qF untracked.tmp "$P/CODEMAP.md" && fail "untracked file excluded" || pass "untracked file excluded"
grep -qF '.vault_link' "$P/CODEMAP.md" && fail ".vault_link excluded" || pass ".vault_link excluded"
eq "headings sorted (LC_ALL=C)" "$(grep '^## ' "$P/CODEMAP.md")" "$(grep '^## ' "$P/CODEMAP.md" | LC_ALL=C sort)"
grep -qE '20[0-9]{2}-[0-9]{2}-[0-9]{2}|[0-9]{2}:[0-9]{2}:[0-9]{2}' "$P/CODEMAP.md" && fail "no timestamps" || pass "no timestamps"
eq "only CODEMAP.md added to worktree" "$(git -C "$P" status --porcelain)" "$(printf '?? CODEMAP.md\n?? untracked.tmp')"

# Determinism: same tree from a different CWD and a fresh clone gives byte-identical output.
c1="$(cksum < "$P/CODEMAP.md")"
(cd "$P" && "$P/.vault_link/.scripts/codemap_refresh.sh" >/dev/null)
eq "rerun from root identical" "$(cksum < "$P/CODEMAP.md")" "$c1"
git clone -q "$P" "$TMP/clone"; (cd "$TMP/clone" && "$VAULT/.scripts/codemap_refresh.sh" >/dev/null)
eq "clone identical" "$(cksum < "$TMP/clone/CODEMAP.md")" "$c1"

# --help writes nothing.
rm -f "$TMP/clone/CODEMAP.md"; (cd "$TMP/clone" && "$VAULT/.scripts/codemap_refresh.sh" --help >/dev/null); RC=$?
eq "help exit 0" "$RC" 0; [ ! -e "$TMP/clone/CODEMAP.md" ] && pass "help writes nothing" || fail "help writes nothing"
done_
