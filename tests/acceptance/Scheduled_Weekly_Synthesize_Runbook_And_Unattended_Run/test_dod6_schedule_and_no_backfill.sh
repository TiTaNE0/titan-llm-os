#!/usr/bin/env bash
# DoD 6: default schedule Monday 09:00 Israel, previous ISO week, no backfill since W20.
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"
wk() { "$HELPER" week --today "$1"; }
eq "Monday 2026-11-30 -> 2026-W48 (the week that just ended)" "$(wk 2026-11-30)" "2026-W48"
eq "Sunday 2026-11-29 -> 2026-W47" "$(wk 2026-11-29)" "2026-W47"
eq "Monday 2026-11-23 -> 2026-W47" "$(wk 2026-11-23)" "2026-W47"
eq "year boundary 2027-01-04 -> 2026-W53" "$(wk 2027-01-04)" "2026-W53"
eq "Sunday 2026-01-04 -> 2025-W52" "$(wk 2026-01-04)" "2025-W52"
eq "Monday 2026-01-05 -> 2026-W01 (ISO year differs from calendar year)" "$(wk 2026-01-05)" "2026-W01"
"$HELPER" week --today 2026-13-40 >/dev/null 2>&1; eq "impossible date exits 3" "$?" "3"
"$HELPER" week --today garbage >/dev/null 2>&1; eq "malformed date exits 3" "$?" "3"
live="$("$HELPER" week)"; echo "$live" | grep -Eq '^[0-9]{4}-W[0-9]{2}$' && pass "default week prints YYYY-Www" || fail "default week format: $live"
expect="$(python3 -c "import datetime;d=datetime.datetime.now(__import__('zoneinfo').ZoneInfo('Asia/Jerusalem')).date()-datetime.timedelta(days=7);i=d.isocalendar();print('%04d-W%02d'%(i[0],i[1]))" 2>/dev/null)"
[ -n "$expect" ] && eq "default today is the Asia/Jerusalem date" "$live" "$expect"

SB="$TMP/sb"; mk_sandbox "$SB"
p="$(cd "$SB" && ./.vault_link/.scripts/synthesize_run.sh plan --week 2026-W53)"; rc=$?
eq "plan W53 2026 exit 0" "$rc" "0"
echo "$p" | grep -q '^monday=2026-12-28$' && echo "$p" | grep -q '^sunday=2027-01-03$' && pass "W53 bounds" || fail "W53 bounds"
p="$(cd "$SB" && ./.vault_link/.scripts/synthesize_run.sh plan --week 2026-W47)"
eq "plan W47 selects only in-week daily logs" "$(echo "$p" | grep '^log=' | tr '\n' ' ')" "log=04_Logs/2026-11-16.md log=04_Logs/2026-11-22.md "
echo "$p" | grep -q '^logs=2$' && pass "logs=2" || fail "logs count"
( cd "$SB" && ./.vault_link/.scripts/synthesize_run.sh plan --week 2025-W53 ) >/dev/null 2>&1; eq "nonexistent week 2025-W53 exits 3" "$?" "3"
( cd "$SB" && ./.vault_link/.scripts/synthesize_run.sh plan --week 2026-47 ) >/dev/null 2>&1; eq "malformed week exits 3" "$?" "3"
( cd "$SB" && ./.vault_link/.scripts/synthesize_run.sh plan --week 2026-W53x ) >/dev/null 2>&1; eq "trailing junk week exits 3" "$?" "3"

drive_unattended "$SB"
eq "driven run processed exactly W47" "$WEEK" "2026-W47"
eq "only W47 outputs exist (no backfill)" "$(ls "$SB/03_Brain/Weekly_Synthesis" | grep -c 'synthesis\.')" "2"
( cd "$SB" && ./.vault_link/.scripts/synthesize_run.sh plan --week 2026-W47 ) >"$TMP/p6" 2>&1; eq "second plan exits 6" "$?" "6"
grep -q 'status=already_synthesized' "$TMP/p6" && pass "already_synthesized reported" || fail "status line"
rm "$SB/03_Brain/Weekly_Synthesis/2026-W47.synthesis.md"
( cd "$SB" && ./.vault_link/.scripts/synthesize_run.sh plan --week 2026-W47 ) >/dev/null 2>&1; eq "only json left exits 3" "$?" "3"
# Fix 1: a stale facts.jsonl.next blocks plan; recovery is delete-only.
ST="$TMP/stale"; mk_sandbox "$ST"; sw="$ST/03_Brain/Weekly_Synthesis"
write_w47 "$ST"; echo 'not json' >> "$sw/facts.jsonl.next"
syn "$ST" report --week 2026-W47 >/dev/null 2>&1; eq "stale: report with a bad .next exits 3" "$?" "3"
syn "$ST" plan --week 2026-W47 >"$TMP/st.out" 2>"$TMP/st.err"; eq "RED: plan same week with stale .next exits 3, not 6" "$?" "3"
grep -qF 'unresolved facts.jsonl.next' "$TMP/st.err" && pass "stale: stderr names unresolved facts.jsonl.next" || fail "stale: stderr: $(cat "$TMP/st.err")"
eq "stale: nothing on stdout" "$(wc -c < "$TMP/st.out" | tr -d ' ')" "0"
syn "$ST" plan --week 2026-W48 >/dev/null 2>&1; eq "RED: plan next week with stale .next exits 3" "$?" "3"
rm -f "$sw/facts.jsonl.next" "$sw/2026-W47.synthesis.md" "$sw/2026-W47.synthesis.json"
syn "$ST" plan --week 2026-W47 >/dev/null 2>&1; eq "GREEN: after delete-only recovery plan W47 exits 0" "$?" "0"
syn "$ST" plan --week 2026-W48 >/dev/null 2>&1; eq "GREEN: after delete-only recovery plan W48 exits 0" "$?" "0"
write_w47 "$ST"; rm -f "$sw/facts.jsonl.next"
syn "$ST" plan --week 2026-W47 >/dev/null 2>&1; eq "GREEN: valid outputs and no .next still exit 6" "$?" "6"
step2="$(awk '/^### Step 2 - /{on=1;next} /^(###|##) /{on=0} on' "$RUNBOOK")"
echo "$step2" | grep -qF 'Recovery is delete-only' && echo "$step2" | grep -qF 'rerun `/synthesize <W>` interactively' && pass "runbook Step 2 pins delete-only recovery" || fail "runbook Step 2 recovery line"
echo "$step2" | grep -qi 'repair' && fail "runbook Step 2 offers a repair branch" || pass "runbook Step 2 has no repair branch"
# Static pins.
has "$RUNBOOK" 'Monday 09:00' "runbook default schedule"
has "$RUNBOOK" 'No backfill' "runbook no-backfill"
has "$RUNBOOK" 'processing the previous ISO week' "runbook previous week"
has "$RUNBOOK" 'Asia/Jerusalem' "runbook timezone"
has "$PROMPT" 'Monday 09:00' "prompt schedule"
finish
